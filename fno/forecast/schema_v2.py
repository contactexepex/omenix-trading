"""The forecast record of protocol version 2 (change 7 and 8): version 1's record (unchanged, frozen in
`schema.py`) plus three columns: `input_mode` (`close_proxy` for history, `live_1500_proxy` for live 15:00 inputs),
`iv30_status` (`interpolated`, `flagged` or `none`: the day's input quality, kept out of `method_or_version`) and
`generated_at` (when the forecast was computed from its pack, with its time zone; a live forecast counts only if
generated by 15:15 IST on its day)."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, time

from ..models import IST
from .schema import RECORD_COLUMNS, ForecastRecord, ForecastRecordError

RECORD_COLUMNS_V2 = RECORD_COLUMNS + ("input_mode", "iv30_status", "generated_at")
INPUT_MODES = ("close_proxy", "live_1500_proxy")
IV30_STATUSES = ("interpolated", "flagged", "none")
GENERATION_DEADLINE = time(15, 15)


@dataclass(frozen=True)
class ForecastRecordV2:
    record: ForecastRecord  # every v1 field and check
    input_mode: str
    iv30_status: str
    generated_at: datetime

    def __post_init__(self):
        if self.input_mode not in INPUT_MODES:
            raise ForecastRecordError(f"input_mode must be one of {INPUT_MODES}, not {self.input_mode!r}")
        if self.iv30_status not in IV30_STATUSES:
            raise ForecastRecordError(f"iv30_status must be one of {IV30_STATUSES}, not {self.iv30_status!r}")
        if self.generated_at.tzinfo is None:
            raise ForecastRecordError("generated_at must carry its time zone")

    @property
    def on_time(self) -> bool:
        """Generated from its pack by 15:15 IST on its day (anti-look-ahead deadline; a later Git push is transport)."""
        deadline = datetime.combine(self.record.date, GENERATION_DEADLINE, tzinfo=IST)
        return self.generated_at <= deadline

    def row(self) -> dict[str, str]:
        extra = {"input_mode": self.input_mode, "iv30_status": self.iv30_status,
                 "generated_at": self.generated_at.isoformat()}  # fmt: skip
        return self.record.row() | extra

    @classmethod
    def from_row(cls, row: dict[str, str]) -> ForecastRecordV2:
        if tuple(row) != RECORD_COLUMNS_V2:
            raise ForecastRecordError(f"columns must be {RECORD_COLUMNS_V2}")
        base = ForecastRecord.from_row({c: row[c] for c in RECORD_COLUMNS})
        try:
            generated = datetime.fromisoformat(row["generated_at"])
        except ValueError as error:
            raise ForecastRecordError(f"bad generated_at {row['generated_at']!r}") from error
        return cls(base, row["input_mode"], row["iv30_status"], generated)
