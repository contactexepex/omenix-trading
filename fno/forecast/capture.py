"""The daily live forecast capture under protocol version 2 (stories G2-G3; GitHub Actions, no AI).

For a trading day: read the canonical A4 snapshot (Groww's dataset first, then NSE's), build the live pack (15:00:00
cutoff per field), check the gates, and compute the three baselines and Book 1 from the pack. Write the pack and the
records once under `research/forecasts/live_v2/<YYYY>/`, and print the receipt line (pack hash, records hash,
generation time) that the Actions run's log and run summary lock. A live forecast counts only if generated by 15:15
IST (`ForecastRecordV2.on_time`); the later Git push is transport. Missing inputs give "no forecast", never a guess.
"""

from __future__ import annotations

import hashlib
from collections.abc import Callable
from dataclasses import dataclass
from datetime import date, datetime
from pathlib import Path

from ..constants import BOOK1_RULES, FORECAST_QUESTIONS, SESSION_MUHURAT
from ..models import IST
from ..quotes.recorder import DATASET, NONE_MARKER, NSE_DATASET, QuoteSnapshotRecorder
from ..research_data.calendar import SessionCalendar
from ..research_data.panel_reader import NiftyPanel
from ..storage.raw_store import RawFileStore
from .baselines import BaseRateBaseline, RiskNeutralBaseline
from .book1_method import book1_probabilities, method_label
from .closes_source import DailyClosesSource, OfficialCloses
from .iv30 import PanelAtmIv30
from .live_history import LiveForecastHistory, stale_history, stale_iv30_history
from .live_pack import CUTOFF, LIVE_MODE, LivePack, LivePackBuilder, SnapshotFiles
from .models import ModelBaseline
from .record_files import records_csv_v2
from .schema import ForecastRecord
from .schema_v2 import ForecastRecordV2

LIVE_FOLDER = "research/forecasts/live_v2"
SNAPSHOT_DATASETS = (DATASET, NSE_DATASET)  # A4's canonical Groww snapshot first, then NSE's (story O6)
LINE = "Omenix F&O forecasts v2 (GitHub Actions): {day}: {result}"


class CaptureRefused(RuntimeError):
    """The day's files already exist with different content: records are written once."""


def load_snapshot(store: RawFileStore, day: date) -> SnapshotFiles | None:
    for dataset in SNAPSHOT_DATASETS:
        marker = store.get(QuoteSnapshotRecorder.path(day, f"nifty_{day:%Y%m%d}.canonical", dataset))
        snapshot_id = marker.decode().strip() if marker else NONE_MARKER
        if snapshot_id == NONE_MARKER:
            continue
        csv_bytes = store.get(QuoteSnapshotRecorder.path(day, f"{snapshot_id}.csv", dataset))
        meta_bytes = store.get(QuoteSnapshotRecorder.path(day, f"{snapshot_id}.meta.json", dataset))
        if csv_bytes and meta_bytes:
            return SnapshotFiles(snapshot_id, dataset, csv_bytes, meta_bytes)
    return None


def _empty_snapshot() -> SnapshotFiles:
    return SnapshotFiles("none", "none", b"", b"{}")


def live_probabilities(history: LiveForecastHistory, gates: list[str]) -> dict[str, dict[str, float | None]]:
    day = history.pack.day
    by = {RiskNeutralBaseline.name: RiskNeutralBaseline(history).probabilities(day)}
    none = dict.fromkeys(FORECAST_QUESTIONS)
    stale = "history_stale" in gates
    by[BaseRateBaseline.name] = none if stale else BaseRateBaseline(history).probabilities(day)
    if "iv30_history_stale" in gates:
        by[BaseRateBaseline.name] = by[BaseRateBaseline.name] | {"q5_rv20_below_atm_iv30": None}
    by[ModelBaseline.name] = none if stale else ModelBaseline(history).probabilities(day)
    by[BOOK1_RULES] = book1_probabilities(by)
    return by


@dataclass
class LiveCapture:
    root: Path
    quotes: RawFileStore
    closes: DailyClosesSource
    panel: Callable[[], NiftyPanel]  # past days' panel (question 5's IV30 history), read only when a pack is built
    calendar: SessionCalendar
    estimator: PanelAtmIv30
    builder: LivePackBuilder
    calendar_sha256: str
    clock: Callable[[], datetime]

    def capture(self, day: date) -> list[str]:
        if self.calendar.session_kind(day) in (None, SESSION_MUHURAT):
            return [LINE.format(day=day, result="not a trading day; nothing recorded")]
        closes = self.closes.closes()
        pack = self._pack(day, closes)
        history = LiveForecastHistory(pack, closes, self.panel(), self.calendar, self.estimator)
        gates = stale_history(closes, self.calendar, day) + stale_iv30_history(history, day)
        pack.problems += gates
        generated = self.clock()
        records = self._records(pack, live_probabilities(history, gates), generated)
        text = records_csv_v2(records)
        written = self._write(day, pack, text)
        counted = sum(r.record.probability is not None for r in records)
        result = f"{written}; {counted} of {len(records)} probabilities; iv30 {pack.iv30_status}"
        problems = f"; inputs: {'; '.join(sorted(pack.problems))}" if pack.problems else ""
        records_sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
        receipt = f"receipt: {day} pack {pack.sha256} records {records_sha} generated_at {generated.isoformat()}"
        return [LINE.format(day=day, result=result + problems), receipt]

    def _pack(self, day: date, closes: OfficialCloses) -> LivePack:
        files = load_snapshot(self.quotes, day)
        supplied = closes.through(day)
        coverage = {"source": closes.source, "through": max(supplied).isoformat() if supplied else "",
                    "sha256": OfficialCloses.table_sha256(supplied)}  # fmt: skip
        pack = self.builder.build(day, files or _empty_snapshot(), coverage, self.calendar_sha256)
        if files is None:
            pack.problems.append("no canonical A4 snapshot")
        return pack

    @staticmethod
    def _records(pack: LivePack, by: dict, generated: datetime) -> list[ForecastRecordV2]:
        cutoff = datetime.combine(pack.day, CUTOFF, tzinfo=IST)
        labels = {name: f"{name}/v1" for name in by} | {BOOK1_RULES: method_label()}
        return [
            ForecastRecordV2(
                ForecastRecord(name, pack.day, cutoff, q, values[q], labels[name], pack.sha256),
                LIVE_MODE,
                pack.iv30_status,
                generated,
            )  # fmt: skip
            for name, values in sorted(by.items())
            for q in FORECAST_QUESTIONS
        ]

    def _write(self, day: date, pack: LivePack, text: str) -> str:
        folder = self.root / LIVE_FOLDER / f"{day:%Y}"
        pack_path, records_path = folder / f"{day.isoformat()}_pack.json", folder / f"{day.isoformat()}_forecasts.csv"
        if records_path.exists():
            if pack_path.read_bytes() != pack.canonical():
                raise CaptureRefused(f"{pack_path} already holds a different pack; records are written once")
            return "already recorded"
        folder.mkdir(parents=True, exist_ok=True)
        pack_path.write_bytes(pack.canonical())
        records_path.write_text(text, encoding="utf-8")
        return "recorded"
