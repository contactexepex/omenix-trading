"""Forecast v2's records and the AI books' sealed answers.

- Book 1 and the baselines: one row per (forecaster, question), each generated by `GENERATION_DEADLINE` (protocol v2's
  own in-file rule). A blank probability is still a row: counted and shown, never a health failure (G9's rule).
- An AI book: its commitment reached GitHub by `receipt_deadline` (F1's push receipt); its reveal and records are only
  checked for presence by the collection end (judge 164 addendum 1). A book that was not fired shows the fire log's
  reason."""

from __future__ import annotations

import csv
import io
from datetime import date, datetime

from ..ai.paths import commitment_path, fired_path, records_path, reveal_path, rules_path
from ..ai.timing import receipt_deadline, reveal_deadline
from ..constants import HEALTH_MISSED, HEALTH_OK
from .evidence import Evidence
from .model import CheckResult, Deadline, EvidenceUnknown, SessionCheck, absent, judged


class ForecastRowsCheck(SessionCheck):
    def __init__(self, evidence: Evidence, expected_rows: int, deadline: Deadline):
        self.evidence, self.expected_rows, self.deadline = evidence, expected_rows, deadline

    def check(self, session: date, now: datetime) -> CheckResult:
        path = rules_path(session)
        text = self.evidence.text(path)
        if text is None:
            return absent(now, reveal_deadline(session), "never ran: no records")
        rows = list(csv.DictReader(io.StringIO(text)))
        blank = sum(1 for row in rows if not (row.get("probability") or "").strip())
        pairs = {(row.get("book"), row.get("question")) for row in rows}
        if len(rows) != self.expected_rows or len(pairs) != len(rows):
            return CheckResult(
                HEALTH_MISSED, f"{len(pairs)} distinct of {self.expected_rows} rows ({len(rows)} written)"
            )
        try:
            latest = max(datetime.fromisoformat(row["generated_at"]) for row in rows)
        except (KeyError, TypeError, ValueError):
            raise EvidenceUnknown(f"{path}: a generated_at is missing or unreadable") from None
        result = judged(latest, self.deadline.on(session), "last generated")
        return CheckResult(result.status, f"{result.detail}; {blank} of {len(rows)} blank")


class AiBookCheck(SessionCheck):
    def __init__(self, evidence: Evidence, book: str):
        self.evidence, self.book = evidence, book

    def check(self, session: date, now: datetime) -> CheckResult:
        fired = self.evidence.json(fired_path(session))
        if fired is None:
            return absent(now, receipt_deadline(session), "never ran: no fire log")
        entry = fired.get(self.book)
        if not entry:
            return CheckResult(HEALTH_MISSED, "not in the fire log")
        if not entry.get("fired"):
            return CheckResult(HEALTH_MISSED, f"not fired: {entry.get('reason', 'no reason recorded')}")
        if self.evidence.text(commitment_path(session, self.book)) is None:
            return absent(now, receipt_deadline(session), "no commitment")
        sealed = judged(self.evidence.file_pushed_at(commitment_path(session, self.book)), receipt_deadline(session),
                        "commitment pushed")  # fmt: skip
        if sealed.status != HEALTH_OK:
            return sealed
        unrevealed = [p for p in (reveal_path(session, self.book), records_path(session, self.book))
                      if self.evidence.text(p) is None]  # fmt: skip
        if unrevealed:
            return absent(now, reveal_deadline(session), f"no {', '.join(p.rsplit('/', 1)[1] for p in unrevealed)}")
        return sealed
