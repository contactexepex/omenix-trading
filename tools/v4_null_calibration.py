"""Protocol v4's pre-registered null calibration (PROTOCOL_v4.md section 5; ChatGPT review 99, finding 1).

Seeded and deterministic. For each dependence kind, block length L in (5, 10, 20) and n in (2L, 125), it draws mean-zero
synthetic loss differences and records how often each one-sided test rejects at protocol v4's real thresholds. Kinds:
i.i.d. normal; overlapping horizon (a moving sum of L/2 shocks, as 5- and 20-session targets overlap); AR(1) with
phi 0.5; and right- and left-skewed (centred lognormal), because QLIKE differences are skewed. Tolerance: nominal +
2 Monte Carlo SE. The bootstrap tests use B = 2,000 here (10,000 in scoring) to keep the run under ten minutes.

    python tools/v4_null_calibration.py            # writes research/forecasts/v4_null_calibration.{json,md}
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from fno.forecast_v4.bootstrap import one_sided_test  # noqa: E402
from fno.forecast_v4.confirmatory import batch_means_p, studentized_bootstrap_p  # noqa: E402

SEED = 20261015
SERIES = 1_000
BOOTSTRAP_RESAMPLES = 2_000
KINDS = ("iid", "overlapping", "ar1", "skew_right", "skew_left")
BLOCKS = (5, 10, 20)
THRESHOLDS = (0.02 / 15, 0.03 / 15, 0.004, 0.01, 0.02, 0.03, 0.05)  # Holm's first steps at looks 1 and 2, then up
TESTS = ("centred_rev0", "batch_means_t", "studentized_bootstrap", "confirmatory_max")
OUT = ROOT / "research" / "forecasts" / "v4_null_calibration"
AR_PHI, AR_BURN = 0.5, 200


def null_series(kind: str, n: int, block: int, rng: np.random.Generator) -> np.ndarray:
    if kind == "iid":
        return rng.standard_normal(n)
    if kind == "overlapping":
        span = max(block // 2, 1)
        return np.convolve(rng.standard_normal(n + span - 1), np.ones(span), "valid")
    if kind == "ar1":
        shocks, x = rng.standard_normal(n + AR_BURN), np.zeros(n + AR_BURN)
        for t in range(1, n + AR_BURN):
            x[t] = AR_PHI * x[t - 1] + shocks[t]
        return x[AR_BURN:]
    skewed = np.exp(rng.standard_normal(n)) - math.exp(0.5)  # mean zero, right-skewed
    return skewed if kind == "skew_right" else -skewed


def p_values(x: np.ndarray, block: int, k: int, resamples: int) -> dict[str, float]:
    batch = batch_means_p(x, block)
    student = studentized_bootstrap_p(x, block, k, resamples)
    centred = one_sided_test(x, block, k, resamples).p_value
    return {"centred_rev0": centred, "batch_means_t": batch, "studentized_bootstrap": student,
            "confirmatory_max": max(batch, student)}  # fmt: skip


def tolerance(rate: float, series: int) -> float:
    return rate + 2 * math.sqrt(rate * (1 - rate) / series)


def run_cell(kind: str, block: int, n: int, cell: int, series: int, resamples: int) -> dict:
    rng = np.random.default_rng(np.random.SeedSequence([SEED, 99, cell]))
    rows = [p_values(null_series(kind, n, block, rng), block, i + 1, resamples) for i in range(series)]
    rates = {test: [sum(r[test] <= a for r in rows) / series for a in THRESHOLDS] for test in TESTS}
    return {"kind": kind, "block": block, "n": n, "rates": rates}


def run(series: int = SERIES, resamples: int = BOOTSTRAP_RESAMPLES) -> list[dict]:
    cells = [(kind, block, n) for kind in KINDS for block in BLOCKS for n in (2 * block, 125)]
    return [run_cell(kind, block, n, i, series, resamples) for i, (kind, block, n) in enumerate(cells)]


def markdown(cells: list[dict], series: int) -> str:
    head = "| kind | L | n | test | " + " | ".join(f"{a:.4g}" for a in THRESHOLDS) + " |"
    lines = [
        "# Protocol v4: null calibration of the one-sided tests (generated by `tools/v4_null_calibration.py`)",
        "",
        f"{series:,} seeded mean-zero series per cell; rejection rate at each threshold; **bold** = above nominal + 2 "
        f"Monte Carlo SE. Bootstrap B = {BOOTSTRAP_RESAMPLES:,}.",
        "",
        head,
        "|" + "---|" * (4 + len(THRESHOLDS)),
    ]
    for cell in cells:
        for test in TESTS:
            marks = [_mark(rate, a, series) for rate, a in zip(cell["rates"][test], THRESHOLDS, strict=True)]
            lines.append(f"| {cell['kind']} | {cell['block']} | {cell['n']} | {test} | " + " | ".join(marks) + " |")
    return "\n".join(lines) + "\n"


def _mark(rate: float, threshold: float, series: int) -> str:
    text = f"{rate:.3f}"
    return f"**{text}**" if rate > tolerance(threshold, series) else text


def main() -> None:
    cells = run()
    meta = {"seed": SEED, "series": SERIES, "bootstrap_resamples": BOOTSTRAP_RESAMPLES, "thresholds": THRESHOLDS}
    OUT.with_suffix(".json").write_text(json.dumps({**meta, "cells": cells}, indent=1) + "\n", encoding="utf-8")
    OUT.with_suffix(".md").write_text(markdown(cells, SERIES), encoding="utf-8")


if __name__ == "__main__":
    main()
